"""Security tests for source-only, non-authorizing signed-review receipt verifier.

Any keypair in this fixture is generated by THIS TEST. No fixture signature
constitutes independently authenticated review of a real Vera memory.
"""
from __future__ import annotations

import base64
import hashlib
import json

import pytest
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

from vera_core.signed_review_attestation import (
    ReviewAttestationRejected, VerifiedReviewAttestation,
    verify_signed_review_attestation,
)

SCHEMA = "VERA_MONO_REVIEW_ATTESTATION_V1"
DOMAIN = b"VERA_MONO_REVIEW_ATTESTATION_V1\x00"
NOW = 1_790_000_000
EXPECTED = {
    "project_id": "synthetic-project",
    "identity_id": "synthetic-identity",
    "state_root_sha256": "a" * 64,
    "record_id": "working-rule-2",
    "record_digest": "b" * 64,
    "memory_head": "c" * 64,
    "privacy_ref": "SYNTHETIC_NONPRIVATE",
    "association_id": "association-7",
    "cue_event_id": "cue-18",
    "use_evidence_id": "use-18",
}
FIELDS = frozenset((*EXPECTED, "issued_at", "expires_at", "review_evidence_ref", "disposition"))


def _serialize(value):
    return json.dumps(value,sort_keys=True,separators=(",",":"),ensure_ascii=True,allow_nan=False).encode("utf8")


def _b64(data):
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def _signed(key, *, overrides=None, envelope_overrides=None):
    payload=dict(EXPECTED,issued_at=NOW-5,expires_at=NOW+300,
                 review_evidence_ref="qualified-review-case-1",disposition="ADMITTED")
    payload.update(overrides or {})
    public=key.public_key().public_bytes(Encoding.Raw,PublicFormat.Raw)
    key_id=hashlib.sha256(public).hexdigest()
    unsigned={"schema":SCHEMA,"signer_key_id":key_id,"payload":payload}
    signature=key.sign(DOMAIN+_serialize(unsigned))
    capsule={**unsigned,"signature":_b64(signature)}
    capsule.update(envelope_overrides or {})
    return _serialize(capsule),public


def _verify(capsule,pub,**expected_overrides):
    expected={**EXPECTED,**expected_overrides}
    return verify_signed_review_attestation(capsule,trusted_public_key_bytes=pub,
        expected_project_id=expected["project_id"],expected_identity_id=expected["identity_id"],
        expected_state_root_sha256=expected["state_root_sha256"],
        expected_record_id=expected["record_id"],expected_record_digest=expected["record_digest"],
        expected_memory_head=expected["memory_head"],expected_privacy_ref=expected["privacy_ref"],
        expected_association_id=expected["association_id"],expected_cue_event_id=expected["cue_event_id"],
        expected_use_evidence_id=expected["use_evidence_id"],now_unix=NOW)


def test_exact_signed_record_and_use_is_verified_but_grants_no_authority():
    private=Ed25519PrivateKey.generate()
    capsule,pub=_signed(private)
    result=_verify(capsule,pub)
    assert type(result) is VerifiedReviewAttestation
    assert result.signer_key_id==hashlib.sha256(pub).hexdigest()
    assert result.review_evidence_ref=="qualified-review-case-1"
    assert result.authorization_effect=="NONE"
    assert result.claim_ceiling=="SIGNATURE_ONLY_NOT_INDEPENDENT_REVIEW"


@pytest.mark.parametrize("changed",list(EXPECTED))
def test_signature_must_bind_exact_project_identity_memory_scope_and_one_time_use(changed):
    private=Ed25519PrivateKey.generate()
    capsule,pub=_signed(private)
    with pytest.raises(ReviewAttestationRejected):
        _verify(capsule,pub,**{changed:EXPECTED[changed]+"-wrong"})


def test_wrong_trusted_key_fails_even_with_self_issued_public_key_inside_capsule():
    capsule,_=_signed(Ed25519PrivateKey.generate())
    other=Ed25519PrivateKey.generate().public_key().public_bytes(Encoding.Raw,PublicFormat.Raw)
    with pytest.raises(ReviewAttestationRejected):
        _verify(capsule,other)


def test_mutated_record_content_and_review_cannot_reuse_signature():
    key=Ed25519PrivateKey.generate()
    raw,pub=_signed(key)
    decoded=json.loads(raw)
    decoded["payload"]["review_evidence_ref"]="fake-owner-says-yes"
    with pytest.raises(ReviewAttestationRejected):
        _verify(_serialize(decoded),pub)


@pytest.mark.parametrize("fields",[
    {"disposition":"QUARANTINED"},
    {"disposition":"UNKNOWN"},
    {"issued_at":NOW+10,"expires_at":NOW+100},
    {"issued_at":NOW-601,"expires_at":NOW+100},
    {"issued_at":NOW-100,"expires_at":NOW-1},
    {"issued_at":True},
    {"expires_at":float("nan")},
    {"review_evidence_ref":""},
])
def test_bad_time_status_or_review_reference_fails_closed(fields):
    key=Ed25519PrivateKey.generate()
    if "expires_at" in fields and isinstance(fields["expires_at"],float):
        # NaN is illegal even before signature encoding, cannot be a valid receipt.
        with pytest.raises(ValueError):
            _signed(key,overrides=fields)
        return
    capsule,pub=_signed(key,overrides=fields)
    with pytest.raises(ReviewAttestationRejected):
        _verify(capsule,pub)


def test_dangerous_extra_or_ambiguous_json_is_rejected():
    key=Ed25519PrivateKey.generate()
    capsule,pub=_signed(key)
    assert capsule.startswith(b"{")
    decoded=json.loads(capsule)
    decoded["payload"]["authorized_tool_effect"]="enable-remote-control"
    with pytest.raises(ReviewAttestationRejected):
        _verify(_serialize(decoded),pub)
    # Duplicate keys cannot be read by different JSON consumers differently.
    duplicate=capsule.replace(b'"schema":',b'"schema":"OTHER","schema":',1)
    with pytest.raises(ReviewAttestationRejected):
        _verify(duplicate,pub)
    with pytest.raises(ReviewAttestationRejected):
        _verify(b" " + capsule,pub)


def test_noncanonical_base64_bad_size_and_missing_public_key_are_rejected():
    key=Ed25519PrivateKey.generate()
    capsule,pub=_signed(key)
    decoded=json.loads(capsule)
    decoded["signature"]+="="
    with pytest.raises(ReviewAttestationRejected):
        _verify(_serialize(decoded),pub)
    with pytest.raises(ReviewAttestationRejected):
        _verify(capsule,b"not-a-public-key")
    with pytest.raises(ReviewAttestationRejected):
        _verify(b"x"*10000,pub)


